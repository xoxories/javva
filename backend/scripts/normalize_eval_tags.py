"""Normalize Indonesian-language tags in eval_cases.json to English.

Some ID-language eval cases generated by Gemini ended up with tags in
Indonesian (e.g. `akun-demo`, `verifikasi-akun`) despite the prompt
requiring English-only tags. This script maps Indonesian stems to
English while preserving kebab-case formatting, and writes the result
back in-place.

Strategy:
  1) Whole-tag overrides for known compounds where word-order needs
     flipping (e.g. `akun-demo` -> `demo-account` rather than the
     awkward `account-demo` you'd get from word-by-word).
  2) Word-by-word fallback using a stem translation table for any
     compound not in the override map.
  3) Tags that are already English pass through unchanged. Re-running
     this script is a no-op.

Usage:
    # Default: normalize backend/data/eval_cases.json in-place
    uv run python scripts/normalize_eval_tags.py

    # Preview without writing
    uv run python scripts/normalize_eval_tags.py --dry-run

    # Explicit input/output paths
    uv run python scripts/normalize_eval_tags.py --in foo.json --out bar.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from rich.console import Console

console = Console()

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PATH = PROJECT_ROOT / "data" / "eval_cases.json"


# Whole-tag overrides — used when word-order in English differs from
# Indonesian (Indonesian: head-modifier; English: modifier-head).
COMPOUND_OVERRIDES: dict[str, str] = {
    "verifikasi-akun": "account-verification",
    "akun-demo": "demo-account",
    "akun-live": "live-account",
    "akun-terkunci": "locked-account",
    "akun-diblokir": "blocked-account",
    "akun-ditangguhkan": "suspended-account",
    "akun-saya": "my-account",
    "biaya-deposit": "deposit-fee",
    "waktu-penarikan": "withdrawal-time",
    "jenis-akun": "account-type",
    "perbedaan-akun": "account-difference",
    "syarat-akun": "account-requirements",
    "status-akun": "account-status",
    "proses-pendaftaran": "registration-process",
    "lupa-password": "forgot-password",
    "lupa-sandi": "forgot-password",
    "mata-uang": "currency",
    # Word-order corrections (post-translation forms)
    "rejection-kyc": "kyc-rejection",
    "activity-suspicious": "suspicious-activity",
    "activity-tidak-sah": "unauthorized-activity",
}

# Word-by-word stem translation — used as fallback when no compound
# override matches.
STEM_TRANSLATION: dict[str, str] = {
    "akun": "account",
    "verifikasi": "verification",
    "pendaftaran": "registration",
    "penarikan": "withdrawal",
    "setoran": "deposit",
    "keamanan": "security",
    "dukungan": "support",
    "masalah": "issue",
    "proses": "process",
    "pembayaran": "payment",
    "biaya": "fee",
    "kartu": "card",
    "dokumen": "document",
    "syarat": "requirement",
    "perbedaan": "difference",
    "jenis": "type",
    "terkunci": "locked",
    "diblokir": "blocked",
    "ditangguhkan": "suspended",
    "waktu": "time",
    "koneksi": "connection",
    "pengguna": "user",
    "transaksi": "transaction",
    "perdagangan": "trading",
    "aman": "safe",
    "saldo": "balance",
    "lupa": "forgot",
    "sandi": "password",
    "nasabah": "customer",
    "klien": "client",
    "panduan": "guide",
    "cara": "method",
    "bantuan": "help",
    "layanan": "service",
    "pribadi": "personal",
    "alamat": "address",
    "rekening": "account",
    "pasar": "market",
    "mata": "currency",
    "uang": "money",
    "buka": "open",
    "baru": "new",
    "mencurigakan": "suspicious",
    "penolakan": "rejection",
    "aktivitas": "activity",
    "penipuan": "fraud",
    "tidak": "not",
    "sah": "valid",
}


def normalize_tag(tag: str) -> str:
    if tag in COMPOUND_OVERRIDES:
        return COMPOUND_OVERRIDES[tag]
    parts = tag.split("-")
    translated = [STEM_TRANSLATION.get(p, p) for p in parts]
    return "-".join(translated)


def main() -> int:
    parser = argparse.ArgumentParser(description="Normalize ID tags to English.")
    parser.add_argument(
        "--in", dest="in_path", type=Path, default=DEFAULT_PATH,
        help=f"Input path (default: {DEFAULT_PATH})",
    )
    parser.add_argument(
        "--out", dest="out_path", type=Path, default=None,
        help="Output path (default: same as --in, in-place)",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Show what would change without writing",
    )
    args = parser.parse_args()

    in_path: Path = args.in_path
    out_path: Path = args.out_path or in_path

    if not in_path.exists():
        console.print(f"[red]Input file not found: {in_path}[/red]")
        return 1

    cases = json.loads(in_path.read_text(encoding="utf-8"))

    console.rule("[bold]normalize_eval_tags")
    console.print(f"Input:  [cyan]{in_path}[/cyan]   ({len(cases)} cases)")
    console.print(f"Output: [cyan]{out_path}[/cyan]")
    if args.dry_run:
        console.print("[yellow]Mode:   dry-run (no write)[/yellow]")
    console.print()

    total_tags = 0
    changed_tags = 0
    cases_affected = 0
    changes_by_case: dict[str, list[tuple[str, str]]] = {}
    unmapped_stems: set[str] = set()

    for case in cases:
        tags = case.get("tags", [])
        new_tags: list[str] = []
        case_changes: list[tuple[str, str]] = []
        for tag in tags:
            total_tags += 1
            new = normalize_tag(tag)
            if new != tag:
                changed_tags += 1
                case_changes.append((tag, new))
            new_tags.append(new)
            # Detect Indonesian-looking stems that didn't translate
            # (rough heuristic: contains a substring that's clearly Indonesian).
            for part in new.split("-"):
                if part and part not in STEM_TRANSLATION.values():
                    if any(c in part for c in ("kasi", "ngan", "kan", "lah")):
                        unmapped_stems.add(part)
        if case_changes:
            cases_affected += 1
            changes_by_case[case["id"]] = case_changes
        case["tags"] = new_tags

    console.print(f"Total tags scanned:    [cyan]{total_tags}[/cyan]")
    console.print(f"Tags changed:          [cyan]{changed_tags}[/cyan]")
    console.print(f"Cases affected:        [cyan]{cases_affected}[/cyan]\n")

    if changes_by_case:
        sample = list(changes_by_case.items())[:5]
        console.print(f"[bold]Sample changes ({len(sample)} of {len(changes_by_case)}):[/bold]")
        for case_id, changes in sample:
            console.print(f"  [cyan]{case_id}[/cyan]")
            for old, new in changes:
                console.print(f"    {old:32} -> {new}")
        console.print()

    if unmapped_stems:
        console.print(
            "[yellow]Warning — possibly Indonesian stems left after translation: "
            f"{sorted(unmapped_stems)}[/yellow]\n"
            "[dim]Consider adding to STEM_TRANSLATION and rerunning.[/dim]\n"
        )

    if args.dry_run:
        console.print("[yellow](dry-run — file not written)[/yellow]")
    elif changed_tags == 0:
        console.print("[dim](no changes — file not written)[/dim]")
    else:
        out_path.write_text(
            json.dumps(cases, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
        console.print(f"[green]Wrote {out_path}[/green]")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
